"""Export the frozen BG confirmation numbers used by the manuscript."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROJECTION = ROOT / "md/experiment_artifacts/aligned_hardware_BG_empirical_service_confirmation_20261004_results_projection.json"
DEFAULT_RECEIPT = ROOT / "md/experiment_artifacts/aligned_hardware_BG_empirical_service_confirmation_20261004_completion_receipt.json"
DEFAULT_OUTPUT = ROOT / "paper/generated/bg_confirmation_results.tex"


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def _snapshot(summary: Mapping[str, Any]) -> tuple[float, float, float, float, int, int, int, int]:
    pooled = summary["pooled"]
    end = pooled["absolute_snapshots"]["observation_end"]
    factual, replacement = end["factual"], end["replacement"]
    return (
        float(factual["restricted_mean_flow_s"]),
        float(replacement["restricted_mean_flow_s"]),
        float(factual["common_p90_flow_s"]),
        float(replacement["common_p90_flow_s"]),
        int(round(factual["unfinished_jobs"])),
        int(round(replacement["unfinished_jobs"])),
        int(round(pooled["absolute_snapshots"]["arrival_horizon"]["factual"]["unfinished_jobs"])),
        int(round(pooled["absolute_snapshots"]["arrival_horizon"]["replacement"]["unfinished_jobs"])),
    )


def _pct(before: float, after: float) -> str:
    return f"{100.0 * (after / before - 1.0):.2f}\\%"


def build(*, projection: Path = DEFAULT_PROJECTION, receipt: Path = DEFAULT_RECEIPT) -> str:
    data = json.loads(Path(projection).read_text())
    receipt_data = json.loads(Path(receipt).read_text())
    _require(data["phase"] == "confirmation", "BG projection is not a confirmation artifact")
    _require(data["evidence_type"] == "independent_confirmation", "BG confirmation evidence type changed")
    _require(data["execution_checks_passed"] is True, "BG confirmation execution checks did not pass")
    _require(receipt_data["completed_unique_scientific_trajectories"] == 384, "BG confirmation roster is incomplete")
    _require(receipt_data["authentic_exit0_tasks"] == 386, "BG confirmation exit-0 receipt changed")
    _require(receipt_data["new_shadow_references"] == 0 and receipt_data["reused_trajectory_arms"] == 0,
             "BG confirmation contains reused scientific trajectories")
    screens = data["performance_screens"]
    summaries = data["statistics"]["condition_summaries"]
    for condition in ("mean", "empirical"):
        _require(screens[condition]["decision"] == "BG_CONFIRMATION_PERFORMANCE_PASS",
                 f"BG {condition} confirmation gate did not pass")
    rows = {condition: _snapshot(summaries[condition]) for condition in ("mean", "empirical")}
    regressions = {}
    for condition in ("mean", "empirical"):
        classes = summaries[condition]["class_results"]
        _require(len(classes) == 24, f"BG {condition} class roster changed")
        regressions[condition] = (
            sum(float(row["delta_T_mean"]["mean"]) > 0.0 for row in classes),
            sum(float(row["delta_T_common_p90"]["mean"]) > 0.0 for row in classes),
        )
    mean_mw, mean_bg, mean_p90_mw, mean_p90_bg, mean_u1200, mean_bg_u1200, mean_u900, mean_bg_u900 = rows["mean"]
    emp_mw, emp_bg, emp_p90_mw, emp_p90_bg, emp_u1200, emp_bg_u1200, emp_u900, emp_bg_u900 = rows["empirical"]
    lines = [
        "% Generated by algorithm/experiments/bg_confirmation_paper_results.py; do not edit manually.",
        r"\providecommand{\BGConfirmationBlockCount}{12}",
        r"\providecommand{\BGConfirmationTapeCount}{96}",
        r"\providecommand{\BGConfirmationTrajectoryCount}{384}",
        r"\providecommand{\BGConfirmationMeanMW}{%.4f}" % mean_mw,
        r"\providecommand{\BGConfirmationMeanBG}{%.4f}" % mean_bg,
        r"\providecommand{\BGConfirmationMeanRelative}{%s}" % _pct(mean_mw, mean_bg),
        r"\providecommand{\BGConfirmationMeanPNinetyMW}{%.4f}" % mean_p90_mw,
        r"\providecommand{\BGConfirmationMeanPNinetyBG}{%.4f}" % mean_p90_bg,
        r"\providecommand{\BGConfirmationMeanPNinetyRelative}{%s}" % _pct(mean_p90_mw, mean_p90_bg),
        r"\providecommand{\BGConfirmationEmpiricalMW}{%.4f}" % emp_mw,
        r"\providecommand{\BGConfirmationEmpiricalBG}{%.4f}" % emp_bg,
        r"\providecommand{\BGConfirmationEmpiricalRelative}{%s}" % _pct(emp_mw, emp_bg),
        r"\providecommand{\BGConfirmationEmpiricalPNinetyMW}{%.4f}" % emp_p90_mw,
        r"\providecommand{\BGConfirmationEmpiricalPNinetyBG}{%.4f}" % emp_p90_bg,
        r"\providecommand{\BGConfirmationEmpiricalPNinetyRelative}{%s}" % _pct(emp_p90_mw, emp_p90_bg),
        r"\providecommand{\BGConfirmationMeanUnfinishedNineHundredMW}{%d}" % mean_u900,
        r"\providecommand{\BGConfirmationMeanUnfinishedNineHundredBG}{%d}" % mean_bg_u900,
        r"\providecommand{\BGConfirmationEmpiricalUnfinishedNineHundredMW}{%d}" % emp_u900,
        r"\providecommand{\BGConfirmationEmpiricalUnfinishedNineHundredBG}{%d}" % emp_bg_u900,
        r"\providecommand{\BGConfirmationMeanUnfinishedTwelveHundredMW}{%d}" % mean_u1200,
        r"\providecommand{\BGConfirmationMeanUnfinishedTwelveHundredBG}{%d}" % mean_bg_u1200,
        r"\providecommand{\BGConfirmationEmpiricalUnfinishedTwelveHundredMW}{%d}" % emp_u1200,
        r"\providecommand{\BGConfirmationEmpiricalUnfinishedTwelveHundredBG}{%d}" % emp_bg_u1200,
        r"\providecommand{\BGConfirmationMeanCategoryMeanRegressions}{%d}" % regressions["mean"][0],
        r"\providecommand{\BGConfirmationMeanCategoryPNinetyRegressions}{%d}" % regressions["mean"][1],
        r"\providecommand{\BGConfirmationEmpiricalCategoryMeanRegressions}{%d}" % regressions["empirical"][0],
        r"\providecommand{\BGConfirmationEmpiricalCategoryPNinetyRegressions}{%d}" % regressions["empirical"][1],
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--projection", type=Path, default=DEFAULT_PROJECTION)
    parser.add_argument("--receipt", type=Path, default=DEFAULT_RECEIPT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build(projection=args.projection, receipt=args.receipt))


if __name__ == "__main__":
    main()
